--        乌龟服需要「就是不要掩码」时会写 0 行，如 (17904,0,0)、(18271,2,0)、(45550,0,0)）。
--   3) 镜像仓库 TuringKi/turtle-wow-custom → 文件字节数/内容一致，无额外信息。
